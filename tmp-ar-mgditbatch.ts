async function applyPage(payload: any, id: string, apply: (doc: any, byType: (t: string) => any[]) => void) {
  const doc: any = await payload.findByID({ collection: 'pages', id, locale: 'en', depth: 0 })
  const byType = (t: string) => doc.layout.filter((b: any) => b.blockType === t)
  apply(doc, byType)
  const updated = await payload.update({
    collection: 'pages',
    id,
    locale: 'ar',
    data: { hero: doc.hero, meta: doc.meta, layout: doc.layout },
    context: { disableRevalidate: true },
  })
  console.log(`Updated Arabic: ${updated.title}`)
}

function applyStandardBlocks(byType: (t: string) => any[], opts: {
  trustedBrands1: [string, string]
  trustedBrands2: [string, string]
  testimonialsTitle: string
}) {
  const stats = byType('stats')[0]
  if (stats) stats.stats.forEach((s: any, i: number) => { s.label = STAT_LABELS[i] })

  const brandsBlocks = byType('trustedBrands')
  if (brandsBlocks[0]) {
    brandsBlocks[0].title = opts.trustedBrands1[0]
    brandsBlocks[0].subtitle = opts.trustedBrands1[1]
    brandsBlocks[0].ctaText = STANDARD_PARTNER_CTA[0]; brandsBlocks[0].ctaLabel = STANDARD_PARTNER_CTA[1]
  }
  if (brandsBlocks[1]) {
    brandsBlocks[1].title = opts.trustedBrands2[0]
    brandsBlocks[1].subtitle = opts.trustedBrands2[1]
    brandsBlocks[1].ctaText = STANDARD_PARTNER_CTA[0]; brandsBlocks[1].ctaLabel = STANDARD_PARTNER_CTA[1]
  }

  const testimonials = byType('testimonials')[0]
  if (testimonials) {
    testimonials.badge = STANDARD_TESTIMONIALS_BADGE
    testimonials.title = opts.testimonialsTitle
    testimonials.fallbackQuotes.forEach((q: any, i: number) => { q.quote = TESTIMONIAL_QUOTES[i][0]; q.name = TESTIMONIAL_QUOTES[i][1]; q.role = TESTIMONIAL_QUOTES[i][2] })
    testimonials.ctaText = STANDARD_TESTIMONIALS_CTA[0]; testimonials.ctaLabel = STANDARD_TESTIMONIALS_CTA[1]
  }

  const faq = byType('faq')[0]
  if (faq) { faq.ctaText = STANDARD_FAQ_CTA[0]; faq.ctaLabel = STANDARD_FAQ_CTA[1] }
}

